def build(upstream: Path) -> str:
    text = upstream.read_text(encoding="utf-8")
    for old, new in PATCHES:
        n = text.count(old)
        if n != 1:
            raise SystemExit(f"anchor found {n} times (expected 1): {old[:70]!r}")
        text = text.replace(old, new)
    header = "// Autobook template — Fotobuch template + Autobook additions (search for AUTOBOOK).\n"
    return header + text


if __name__ == "__main__":
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else RES / "fotobuch-upstream-v0.3.0.typ"
    (RES / "autobook.typ").write_text(build(src), encoding="utf-8")
    print(f"wrote {RES / 'autobook.typ'}")
